"""DecisionStability runtime contract."""

from __future__ import annotations

from enum import Enum
from typing import List
from pydantic import BaseModel, ConfigDict, Field


class StabilityState(str, Enum):
    """Whether plausible states S* alter the discrete business decision."""
    STABLE = "STABLE"
    UNSTABLE = "UNSTABLE"
    NOT_EVALUATED = "NOT_EVALUATED"
    INSUFFICIENT_STATE_COVERAGE = "INSUFFICIENT_STATE_COVERAGE"


class DecisionStability(BaseModel):
    """Assessment of whether remaining spatial uncertainty impacts the downstream decision."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    scope: str = Field(description="Variable assessed (e.g. city_assignment, geofence_membership)")
    state: StabilityState = Field(description="Stability verdict over plausible state set S*")
    plausible_state_count: int = Field(default=1, description="Number of competing plausible states evaluated")
    competing_outcomes: List[str] = Field(
        default_factory=list,
        description="Different decision outcomes generated by plausible states",
    )
    rationale: str = Field(default="", description="Explanation of stability or instability")

    @property
    def is_stable(self) -> bool:
        return self.state == StabilityState.STABLE
